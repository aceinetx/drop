#[derive(Debug, Clone)]
pub enum Token {
    Eof,
    Identifier(String),
    String(String),
    Colon,
    Semicolon,
    Lparen,
    Rparen,
    Star,
    Lbrace,
    Rbrace,
    Extern,
    Return,
    Fn,
    Comma,
    Const,
    Lbracket,
    Rbracket,
    Number(i64),
    Plus,
    Minus,
    Div,
    Mul,
}
